#!/usr/bin/env node
// Writes trees_titles.js: question titles for every leaf link in trees_data.js (so the page can label deep links offline).
import fs from 'node:fs'; import vm from 'node:vm';
const ctx = { window: {} }; vm.runInNewContext(fs.readFileSync('trees_data.js', 'utf8'), ctx);
const keyOf = f => f.replace(/\.html$/, '').replace(/_interview_guide$|_guide$/, '');
const data = JSON.parse(fs.readFileSync('data/questions.json', 'utf8'));
const files = {}, titles = {};
data.guides.forEach(g => { files[keyOf(g.file)] = g.file; g.questions.forEach(q => titles[keyOf(g.file) + '#' + q.n] = q.q); });
const need = {};
ctx.window.TREES.forEach(t => Object.values(t.n).forEach(n => (n.l || []).forEach(([g, q]) => need[g + '#' + q] = titles[g + '#' + q])));
fs.writeFileSync('trees_titles.js', '// Generated by tools/build_trees.mjs\nwindow.TREE_FILES=' + JSON.stringify(files) + ';\nwindow.TREE_TITLES=' + JSON.stringify(need) + ';\n');
console.log(Object.keys(need).length + ' titles');
