#!/usr/bin/env node
// Regenerates the guides table + headline counts in README.md from the real guide data, so they can never drift.
// Usage: node tools/extract.mjs && node tools/sync_readme.mjs     (run from repo root)
import fs from 'node:fs';

const data = JSON.parse(fs.readFileSync('data/questions.json', 'utf8'));
const keyOf = f => f.replace(/\.html$/, '').replace(/_interview_guide$|_guide$/, '');
const spokenCount = {};
for (const f of fs.existsSync('spoken') ? fs.readdirSync('spoken') : []) {
  const m = fs.readFileSync(`spoken/${f}`, 'utf8').match(/^\s{2}\d+: \{/gm);
  spokenCount[f.replace(/\.js$/, '')] = m ? m.length : 0;
}
const names = {
  terraform: ['Terraform Production', 'State, backends, modules, CI/CD, recovery'],
  kubernetes: ['Kubernetes Production', 'Pods, networking, storage, security, HPA, upgrades'],
  gcp: ['GCP Production', 'IAM, GKE, VPC, Cloud SQL, SCC, FinOps'],
  aws: ['AWS Production', 'IAM, VPC, EKS, RDS, Lambda, cost'],
  azure: ['Azure Production', 'Entra ID, AKS, VNet, Storage, Cost Mgmt'],
  networking: ['Networking Fundamentals', 'TCP/DNS, TLS, routing, eBPF, troubleshooting'],
  linux: ['Linux Systems Admin', 'Processes, performance, security, systemd'],
  database_performance: ['Database Performance', 'Indexing, EXPLAIN, replication, Cloud SQL'],
  container_lifecycle: ['Container Lifecycle & Deployments', 'Docker, deployments, Helm, GitOps'],
  git_production: ['Git in Production', 'Branching, recovery, GitOps, governance'],
  observability: ['Observability & Monitoring', 'Prometheus, Grafana, SLOs, OTel, alerting'],
  cicd: ['CI/CD Pipelines', 'GitHub Actions, ArgoCD, Cloud Build, GitOps'],
  sre_reliability: ['SRE Reliability & Incident Management', 'SLOs, error budgets, incident command, postmortems, chaos'],
  product_management: ['Technical / Platform Product Management', 'Product sense, platform metrics, build-vs-buy, RICE'],
  coding_scripting: ['Coding & Scripting for SRE / Platform', 'Bash, Python, algorithms, API pagination, Go basics'],
  devsecops_security: ['DevSecOps / Cloud & Supply-Chain Security', 'Vault/KMS, SBOM/SLSA, K8s hardening, policy-as-code'],
  behavioral_star: ['Behavioral Interview (STAR)', 'Incidents, leadership, communication, ownership'],
  sre_devops_scenarios: ['Production Scenarios', 'STAR-format incident walkthroughs across SRE/DevOps/Platform'],
  architecture_tradeoffs: ['Staff+ Architecture & Trade-offs', 'Build vs buy, multi-region, tech debt, big bets'],
  openstack: ['OpenStack Private Cloud', 'Nova, Neutron, Cinder, Keystone, Ceph, HA, upgrades, troubleshooting'],
  ansible: ['Ansible', 'Playbooks, roles, inventory, Vault, Jinja2, error handling, AWX, testing with Molecule'],
  python_sre: ['Python for SRE & DevOps', 'Scripting, CLI tools, cloud SDKs, concurrency, testing, packaging, ops automation, observability, patterns'],
  helm: ['Helm', 'Charts, templates, values, releases, repositories, CI/CD, security, troubleshooting'],
  ai: ['AI, LLM & MLOps', 'RAG, agents, model serving, GPUs on K8s, evaluation, LLM security, cost'],
  system_design: ['System Design', 'URL shortener, rate limiter, cache, multi-region K8s, IDP'],
};

let totalSpoken = 0;
const rows = data.guides.map((g, i) => {
  const k = keyOf(g.file), [name, topics] = names[k] || [g.title, ''];
  const sp = spokenCount[k] || 0; totalSpoken += sp;
  return `| ${i + 1} | ${name} | \`${g.file}\` | ${g.count} | ${sp || '—'} | [PDF](pdf/${g.file.replace('.html', '.pdf')}) | ${topics} |`;
});
const table = [
  '| # | Guide | File | Questions | Spoken answers | PDF | Topics |',
  '|---|-------|------|-----------|----------------|-----|--------|',
  ...rows,
  `| | **Total** | | **${data.total.toLocaleString('en-US')}** | **${totalSpoken}** | | |`,
].join('\n');

let md = fs.readFileSync('README.md', 'utf8');
const block = `<!-- GUIDES:START (generated by tools/sync_readme.mjs — do not edit by hand) -->\n${table}\n<!-- GUIDES:END -->`;
md = md.replace(/<!-- GUIDES:START[\s\S]*?<!-- GUIDES:END -->/, block);
const headline = `${Math.floor(data.total / 100) * 100}+`.replace(/(\d)(\d{3})\+/, '$1,$2+');
md = md.replace(/<!-- COUNT -->[^<]*<!-- \/COUNT -->/g, `<!-- COUNT -->${headline}<!-- /COUNT -->`);
fs.writeFileSync('README.md', md);
console.log(`README synced: ${data.total} questions in ${data.guides.length} guides, ${totalSpoken} spoken answers, headline ${headline}`);
